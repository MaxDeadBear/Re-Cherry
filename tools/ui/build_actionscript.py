#!/usr/bin/env python3
"""Compile the ActionScript 2 the UI patches into the game's Flash movies (src/ui/actionscript/*.as) into
src/ui/actionscript/actionscript.h, one DoAction body per source.

The compiler is JPEXS FFDec's (https://github.com/jindrapetrik/jpexs-decompiler): each source is imported into a
throwaway one-frame SWF and the DoAction tag it produces is copied out. Run it after editing a source and commit the
header; the build never needs Java or FFDec.

Usage:
  python tools/ui/build_actionscript.py --ffdec path/to/ffdec.jar
"""

import argparse
import glob
import os
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE_DIR = os.path.join(ROOT, "src", "ui", "actionscript")
HEADER = os.path.join(SOURCE_DIR, "actionscript.h")

TAG_END, TAG_SHOW_FRAME, TAG_DO_ACTION = 0, 1, 12


def tag(code, body):
    if len(body) < 0x3F:
        return struct.pack("<H", (code << 6) | len(body)) + body
    return struct.pack("<HI", (code << 6) | 0x3F, len(body)) + body


def placeholder_swf():
    # A 1x1 SWF 8 movie whose only frame holds a DoAction of `stop();`, which FFDec's -importScript replaces.
    rect = bytes([0x08, 0x00])  # nbits 1, every field 0
    body = rect + struct.pack("<HH", 30 << 8, 1)
    body += tag(TAG_DO_ACTION, b"\x07\x00") + tag(TAG_SHOW_FRAME, b"") + tag(TAG_END, b"")
    return b"FWS" + bytes([8]) + struct.pack("<I", 8 + len(body)) + body


def tags(data):
    nbits = data[8] >> 3
    pos = 8 + (5 + 4 * nbits + 7) // 8 + 4
    while pos < len(data):
        header = struct.unpack_from("<H", data, pos)[0]
        code, length = header >> 6, header & 0x3F
        pos += 2
        if length == 0x3F:
            length = struct.unpack_from("<I", data, pos)[0]
            pos += 4
        yield code, data[pos : pos + length]
        pos += length
        if code == TAG_END:
            return


def compile_source(ffdec, source):
    work = tempfile.mkdtemp(prefix="cherry_as_")
    try:
        swf_in = os.path.join(work, "in.swf")
        swf_out = os.path.join(work, "out.swf")
        script_dir = os.path.join(work, "scripts", "frame_1")
        os.makedirs(script_dir)
        with open(swf_in, "wb") as f:
            f.write(placeholder_swf())
        shutil.copyfile(source, os.path.join(script_dir, "DoAction.as"))
        result = subprocess.run(["java", "-jar", ffdec, "-importScript", swf_in, swf_out, work], capture_output=True, text=True)
        if result.returncode != 0 or not os.path.exists(swf_out):
            sys.exit(f"{os.path.basename(source)}: FFDec failed\n{result.stdout}{result.stderr}")
        with open(swf_out, "rb") as f:
            data = f.read()
        if data[:3] != b"FWS":
            sys.exit(f"{os.path.basename(source)}: FFDec wrote a compressed SWF")
        actions = [body for code, body in tags(data) if code == TAG_DO_ACTION]
        if len(actions) != 1 or actions[0] == b"\x07\x00":
            sys.exit(f"{os.path.basename(source)}: the script did not compile\n{result.stdout}{result.stderr}")
        return actions[0]
    finally:
        shutil.rmtree(work, ignore_errors=True)


def symbol(source):
    stem = os.path.splitext(os.path.basename(source))[0]
    return "g_" + "".join(part.capitalize() if i else part for i, part in enumerate(stem.split("_")))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ffdec", required=True, help="path to ffdec.jar")
    args = parser.parse_args()
    out = ["#pragma once", "", "// Generated by tools/ui/build_actionscript.py from src/ui/actionscript/*.as; do not edit.", "", "namespace cherry::ui::actionscript {", ""]
    for source in sorted(glob.glob(os.path.join(SOURCE_DIR, "*.as"))):
        code = compile_source(args.ffdec, source)
        out.append(f"inline constexpr unsigned char {symbol(source)}[] = {{")
        for i in range(0, len(code), 16):
            out.append("    " + "".join(f"0x{b:02X}, " for b in code[i : i + 16]).rstrip())
        out.append("};")
        out.append("")
        print(f"{os.path.basename(source)}: {len(code)} bytes")
    out.append("}  // namespace cherry::ui::actionscript")
    with open(HEADER, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
