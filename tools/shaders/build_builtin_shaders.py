#!/usr/bin/env python3
"""Compile the renderer's own HLSL (src/gpu/shaders/hlsl/) into src/gpu/shaders/builtin_shaders.h.

These are the renderer's shaders, not the game's: the game's go through XenosRecomp (docs/renderer/shaders.md).
Emits DXIL and SPIR-V so the header serves plume's D3D12 and Vulkan backends. Run it after editing a source and
commit the header; the build never needs DXC.

Usage:
  python tools/shaders/build_builtin_shaders.py
"""

import os
import platform
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHADER_DIR = os.path.join(ROOT, "src", "gpu", "shaders")
DXC_DIR = os.path.join(ROOT, "thirdparty", "XenosRecomp", "thirdparty", "dxc-bin", "bin", "x64")
DXC = os.path.join(DXC_DIR, "dxc.exe" if platform.system() == "Windows" else "dxc-linux")

# (source, entry point, profile, symbol prefix)
TARGETS = [
    ("blit.hlsl", "VSMain", "vs_6_0", "g_blitVS"),
    ("blit.hlsl", "PSMain", "ps_6_0", "g_blitPS"),
    ("depth_resolve.hlsl", "VSMain", "vs_6_0", "g_depthResolveVS"),
    ("depth_resolve.hlsl", "PSMain", "ps_6_0", "g_depthResolvePS"),
    ("color_resolve.hlsl", "VSMain", "vs_6_0", "g_colorResolveVS"),
    ("color_resolve.hlsl", "PSMain", "ps_6_0", "g_colorResolvePS"),
    ("ui.hlsl", "VSMain", "vs_6_0", "g_uiVS"),
    ("ui.hlsl", "PSMain", "ps_6_0", "g_uiPS"),
]


def compile_one(source, entry, profile, spirv):
    out = source + (".spv" if spirv else ".dxo")
    # The flags XenosRecomp compiles the guest shaders with (dxc_compiler.cpp), so both share one pipeline layout.
    args = [DXC, "-T", profile, "-E", entry, "-Fo", out, source, "-O3", "-HV", "2021", "-all-resources-bound", "-Qstrip_debug"]
    if spirv:
        args += ["-spirv", "-fvk-use-dx-layout"]
        # Vulkan's NDC Y points the other way; XenosRecomp flips every guest vertex shader the same way. Pixel shaders must not get it.
        if profile.startswith("vs_"):
            args.append("-fvk-invert-y")
    else:
        args.append("-Qstrip_reflect")
    result = subprocess.run(args, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit("dxc failed for {}:{}\n{}".format(source, entry, result.stderr))
    with open(out, "rb") as f:
        data = f.read()
    os.remove(out)
    return data


def emit(f, name, data):
    f.write("inline constexpr unsigned char {}[] = {{\n".format(name))
    for i in range(0, len(data), 16):
        f.write("    " + "".join("0x%02X, " % b for b in data[i:i + 16]) + "\n")
    f.write("};\n\n")


def main():
    if not os.path.isfile(DXC):
        sys.exit("dxc not found at {}\n(git submodule update --init --recursive)".format(DXC))
    header = os.path.join(SHADER_DIR, "builtin_shaders.h")
    with open(header, "w", newline="\n") as f:
        f.write("#pragma once\n\n")
        f.write("// Generated by tools/shaders/build_builtin_shaders.py from src/gpu/shaders/hlsl/; do not edit.\n\n")
        f.write("namespace cherry::gpu::shaders {\n\n")
        for source, entry, profile, prefix in TARGETS:
            path = os.path.join(SHADER_DIR, "hlsl", source)
            dxil = compile_one(path, entry, profile, spirv=False)
            spv = compile_one(path, entry, profile, spirv=True)
            print("{}:{} -> dxil {} bytes, spirv {} bytes".format(source, entry, len(dxil), len(spv)))
            emit(f, prefix + "Dxil", dxil)
            emit(f, prefix + "Spirv", spv)
        f.write("}  // namespace cherry::gpu::shaders\n")
    print("wrote", header)


if __name__ == "__main__":
    main()
